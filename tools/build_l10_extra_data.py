#!/usr/bin/env python3
"""Write docs/source/_static/l10w/l10w-extra-data.js: the data of the L10 lecture page's MPC panel.

The docs-only panels (_static/l10w/l10w-extra.js) are hand-written. The MPC panel draws the 729 plans of the
lecture's MPC section, so it reads the course's stored results instead of a copy typed by hand:

  ../../workspace/enpm818z-fall-2026-carla-python/lecture10/l10_curve.npz                 the lane center
  ../../workspace/enpm818z-fall-2026-carla-python/lecture10/l10_results/mpc_candidates.npz  the 729 plans
  ../../workspace/enpm818z-fall-2026-carla-python/lecture10/l10_results/worked.json        the measured pose

Each plan keeps its three angles, its scores (path error, total) and its predicted rear-axle path every 4th
step of 0.05 s (0.2 s apart, 16 points; steps 20 and 40, where the held angle changes, are among them), in
centimeters. The lane is kept for x from 66 to 102 m, where the panel draws.

Run from the docs repo root:  python3 tools/build_l10_extra_data.py
"""
import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT.parents[1] / "workspace" / "enpm818z-fall-2026-carla-python" / "lecture10"
OUT = ROOT / "docs" / "source" / "_static" / "l10w" / "l10w-extra-data.js"
LANE_HALF = 1.75          # Town03's lanes are 3.5 m wide, as the lecture's figures draw them


def main():
    cv = np.load(SRC / "l10_curve.npz")
    cand = np.load(SRC / "l10_results" / "mpc_candidates.npz")
    pose = json.loads((SRC / "l10_results" / "worked.json").read_text())["mpc"]
    keep = (cv["x"] >= 66) & (cv["x"] <= 102)
    lane = {"x": np.round(cv["x"][keep], 2).tolist(), "y": np.round(cv["y"][keep], 2).tolist(),
            "h": np.round(cv["heading"][keep], 4).tolist()}
    seq = np.round(cand["seq"], 1)
    idx = list(range(0, 61, 4))
    plans = []
    for i in range(len(seq)):
        pts = [[int(round(cand["x"][i][k] * 100)), int(round(cand["y"][i][k] * 100))] for k in idx]
        plans.append([[float(v) + 0.0 for v in seq[i]], round(float(cand["cost_e"][i]), 3), round(float(cand["cost"][i]), 3), pts])
    best = int(np.argmin(cand["cost"]))
    data = {"lane": lane, "lane_half": LANE_HALF, "pose": {k: round(float(pose[k]), 3) for k in ("x", "y", "theta", "v", "s")},
            "grid": [round(float(g), 1) + 0.0 for g in pose["grid"]], "step_idx": idx, "best": best, "plans": plans}
    if len(plans) != 729 or round(float(cand["cost"][best]), 3) != 0.186:
        raise SystemExit("the stored MPC results changed: check the lecture's MPC numbers first")
    OUT.write_text("/* Generated by tools/build_l10_extra_data.py from the course's stored L10 results: the MPC panel's lane,\n"
                   "   pose and 729 plans (angles, path error, score, path every 0.2 s in cm). */\n"
                   "window.L10W_EXTRA = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(plans)} plans, {OUT.stat().st_size // 1024} KB")


if __name__ == "__main__":
    main()
