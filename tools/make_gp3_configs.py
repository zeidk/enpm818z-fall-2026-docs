#!/usr/bin/env python3
"""
make_gp3_configs.py: each team's GP3 values.

Each team gets its own GNSS antenna position on the car and its own GNSS
outage window. The antenna offset enters the GNSS measurement model h and
its Jacobian H, so an EKF copied from another team gives measurably wrong
positions. The seed comes from the year, so the same year always gives the
same table.

    # print the table
    python3 tools/make_gp3_configs.py --year 2026 --teams 5

    # write it into gp3.rst, between the marker comments
    python3 tools/make_gp3_configs.py --year 2026 --teams 5 --inject

    # the YAML lines each team should have, for grading
    python3 tools/make_gp3_configs.py --year 2026 --teams 5 --answers

Ranges:
- dx (forward, m): 1.0 to 1.5 in size, ahead of or behind the car's
  origin; dy (left, m): -0.8 to 0.8, so the antenna stays on the roof. The
  offset is then at least 1 m, larger than the rigs' GNSS noise (5e-6
  degrees, about 0.56 m).
- Outage: starts 30 to 50 s after the first fix and lasts 15 to 25 s,
  inside the 90 s drive.
"""

import argparse
import pathlib
import re
import sys

import numpy as np

BEGIN = ".. GP3-TEAM-CONFIG-BEGIN (generated by tools/make_gp3_configs.py)"
END = ".. GP3-TEAM-CONFIG-END"


def build(year: int, n_teams: int):
    rng = np.random.default_rng(year * 3 + 1)
    teams = []
    for i in range(n_teams):
        dx = round(float(rng.uniform(1.0, 1.5)) * (1 if rng.random() < 0.5 else -1), 2)
        dy = round(float(rng.uniform(-0.8, 0.8)), 2)
        start = round(float(rng.uniform(30.0, 50.0)), 1)
        end = round(start + float(rng.uniform(15.0, 25.0)), 1)
        teams.append({"id": chr(65 + i), "dx": dx, "dy": dy,
                      "outage_start": start, "outage_end": end})
    return teams


def table(teams):
    rows = [".. list-table::", "   :header-rows: 1", "   :class: compact-table", "",
            "   * - Rig", "     - Antenna x (m, forward)", "     - Antenna y (m, left)",
            "     - Outage start (s)", "     - Outage end (s)"]
    for t in teams:
        rows += [f"   * - {t['id']}", f"     - {t['dx']:+.2f}", f"     - {t['dy']:+.2f}",
                 f"     - {t['outage_start']:.1f}", f"     - {t['outage_end']:.1f}"]
    return "\n".join(rows)


def answers(teams):
    out = []
    for t in teams:
        out.append(f"Rig {t['id']}:\n"
                   f"  carla_config.yaml  mounts.gnss_link: x {t['dx']:.2f}, y {-t['dy']:.2f}"
                   f"  (CARLA axes: y right)\n"
                   f"  ekf_config.yaml    antenna_x: {t['dx']:.2f}, antenna_y: {t['dy']:.2f}\n"
                   f"  gp3_launch.py      outage_start_s:={t['outage_start']:.1f}"
                   f" outage_end_s:={t['outage_end']:.1f}")
    return "\n".join(out)


def inject(text, page):
    path = pathlib.Path(page)
    src = path.read_text()
    pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pat.search(src):
        sys.exit(f"markers not found in {page}")
    path.write_text(pat.sub(BEGIN + "\n\n" + text + "\n\n" + END, src))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--year", type=int, required=True)
    ap.add_argument("--teams", type=int, default=5)
    ap.add_argument("--inject", action="store_true")
    ap.add_argument("--answers", action="store_true")
    ap.add_argument("--page", default="docs/source/assignments/gp3.rst")
    a = ap.parse_args()
    teams = build(a.year, a.teams)
    if a.answers:
        print(answers(teams))
    elif a.inject:
        inject(table(teams), a.page)
        print(f"wrote {len(teams)} rows into {a.page}")
    else:
        print(table(teams))


if __name__ == "__main__":
    main()
